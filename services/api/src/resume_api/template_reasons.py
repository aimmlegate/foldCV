def reason_text(reason):
    """The Russian text of a compiler reason; one it does not know gets the general text, never the English."""
    if reason in REASONS:
        return REASONS[reason]
    for start, text in PREFIXES.items():
        if reason.startswith(start):
            return text + reason[len(start):]
    return next((text for start, text in FAMILIES.items() if reason.startswith(start)), FALLBACK)
