/** Writes the FoldCV light palette as CSS: the prototype's tokens.css (first-paint defaults) and the sheet's pinned
 * values. Run from apps/web after a palette change: `node --import tsx tools/theme-tokens.ts`. */
import { writeFileSync } from "node:fs";
import { palette } from "../src/workbench/settings/themes";

const light = palette("foldcv", "light", 100);
const entries = Object.entries(light).map(([token, value]) => `--${token}:${value}`);
writeFileSync(new URL("../../../design/future-editor/visual/tokens.css", import.meta.url),
  `:root{${entries.join(";")};--glass:.95;--ui-body:14px;--ui-small:12px;--ui-title:16px;--serif:Georgia,"Times New Roman",serif;--sans:-apple-system,BlinkMacSystemFont,"Segoe UI",Arial,sans-serif}\n`);
writeFileSync(new URL("../src/workbench/styles/sheet-light.css", import.meta.url),
  `/* Generated by tools/theme-tokens.ts. The resume sheet and the original text keep the light prototype values under every\n   theme: the page is a document, not interface. Inherited colors are declared again here so they resolve with these values. */\n.resume-paper, .source-text-preview { ${entries.join("; ")}; color: var(--ink); color-scheme: light; }\n`);
console.log("Wrote tokens.css and sheet-light.css");
